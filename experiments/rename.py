"""A: alpha-rename every library unit (top-level function/class) to a neutral identifier.

Why: in the toolz pilot 77/116 items were answered correctly WITHOUT any code, because names such
as `take` or `merge` (and memorised library knowledge) make the context unnecessary. Renaming
forces the model to read the definitions in its context.

What is renamed (consistently, via the AST): unit names at definition sites and at every Name /
argument / keyword occurrence in unit sources, item setup and item expression.
Attributes are NOT renamed.  Imports of the library itself are dropped from item setup (all units
are declared in scope).  Comments disappear because sources are regenerated by ast.unparse.

Verification (not assumed): all renamed units of the package are executed in ONE flat namespace
(stdlib imports + module-level statements + renamed units, executed with a retry loop for
definition order). Each renamed item is then executed there, traced again (code objects carry the
filename "<unit:uid>"), and kept only if
  - the answer equals the original item's answer, and
  - the renamed core fragments equal the original core fragments.

  .venv/bin/python experiments/rename.py --data experiments/data/toolz --out experiments/data/toolz_anon
"""
import argparse
import ast
import importlib
import io
import json
import os
import random
import sys
from contextlib import redirect_stdout

sys.path.insert(0, os.path.dirname(__file__))
from build_items import SKIP_MODULE_PARTS  # noqa: E402

FLAT_SKIP_FILES = {"__init__.py", "_signatures.py"}  # package glue / signature registry


class Renamer(ast.NodeTransformer):
    def __init__(self, mapping):
        self.m = mapping

    def visit_Name(self, node):
        if node.id in self.m:
            node.id = self.m[node.id]
        return node

    def _def(self, node):
        if node.name in self.m:
            node.name = self.m[node.name]
        self.generic_visit(node)
        return node

    visit_FunctionDef = visit_AsyncFunctionDef = visit_ClassDef = _def

    def visit_arg(self, node):
        if node.arg in self.m:
            node.arg = self.m[node.arg]
        self.generic_visit(node)
        return node

    def visit_keyword(self, node):
        if node.arg in self.m:
            node.arg = self.m[node.arg]
        self.generic_visit(node)
        return node


def rename_src(src, mapping, mode="exec"):
    tree = Renamer(mapping).visit(ast.parse(src, mode=mode))
    return ast.unparse(ast.fix_missing_locations(tree))


def drop_lib_imports(setup, lib):
    if not setup.strip():
        return setup
    body = [st for st in ast.parse(setup).body
            if not (isinstance(st, ast.ImportFrom) and (st.module or "").split(".")[0] == lib)
            and not (isinstance(st, ast.Import) and any(a.name.split(".")[0] == lib for a in st.names))]
    return "".join(ast.unparse(st) + "\n" for st in body)


# ---------------------------------------------------------------- flat verification namespace
def is_lib_import(st, lib):
    if isinstance(st, ast.ImportFrom):
        return st.level > 0 or (st.module or "").split(".")[0] == lib
    if isinstance(st, ast.Import):
        return any(a.name.split(".")[0] == lib for a in st.names)
    return False


def build_flat_namespace(pkg_dir, rel_root, lib, units, mapping):
    stmts = []  # (filename_for_compile, source)
    for root, dirs, files in os.walk(pkg_dir):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_MODULE_PARTS and not d.startswith("__"))
        for fn in sorted(files):
            if not fn.endswith(".py") or fn in FLAT_SKIP_FILES:
                continue
            rel = os.path.relpath(os.path.join(root, fn), rel_root)
            if any(p in SKIP_MODULE_PARTS for p in rel[:-3].split(os.sep)):
                continue
            tree = ast.parse(open(os.path.join(root, fn), encoding="utf-8").read())
            for st in tree.body:
                if is_lib_import(st, lib):
                    continue
                if isinstance(st, ast.Assign) and any(
                        isinstance(t, ast.Name) and t.id == "__all__" for t in st.targets):
                    continue
                if isinstance(st, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    uid = f"{rel}::{st.name}"
                    fname = f"<unit:{uid}>"
                else:
                    fname = f"<glob:{rel}>"
                src = ast.unparse(ast.fix_missing_locations(Renamer(mapping).visit(st)))
                stmts.append((fname, src))
    ns = {"__name__": "flat_" + lib, "__builtins__": __builtins__}
    pending, failed = stmts, []
    for _ in range(10):  # retry loop: definition order across files is unknown
        failed = []
        for fname, src in pending:
            try:
                exec(compile(src, fname, "exec"), ns)
            except Exception as e:
                failed.append((fname, src, e))
        if not failed or len(failed) == len(pending):
            break
        pending = [(f, s) for f, s, _ in failed]
    return ns, [(f, repr(e)) for f, _, e in failed]


class FlatTracer:
    def __init__(self):
        self.hits = []

    def _profile(self, frame, event, arg):
        if event == "call":
            fn = frame.f_code.co_filename
            if fn.startswith("<unit:") and fn[6:-1] not in self.hits:
                self.hits.append(fn[6:-1])

    def __enter__(self):
        self.hits = []
        sys.setprofile(self._profile)
        return self

    def __exit__(self, *exc):
        sys.setprofile(None)


def run_flat(ns, setup, expr):
    local = dict(ns)
    tr = FlatTracer()
    with redirect_stdout(io.StringIO()), tr:
        if setup.strip():
            exec(compile(setup, "<item>", "exec"), local)
        result = eval(compile(expr, "<item>", "eval"), local)
    return repr(result), tr.hits


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lib", default="toolz")
    ap.add_argument("--data", default="experiments/data/toolz")
    ap.add_argument("--out", default="experiments/data/toolz_anon")
    ap.add_argument("--seed", type=int, default=29)
    args = ap.parse_args()

    units = json.load(open(args.data + "_units.json", encoding="utf-8"))
    items = [json.loads(l) for l in open(args.data + "_items.jsonl", encoding="utf-8")]
    rng = random.Random(args.seed)

    # neutral names, numbered in random order so numbering carries no file/position information
    names = sorted({u["name"] for u in units.values()})
    nums = rng.sample(range(100, 1000), len(names))
    kind = {}
    for u in units.values():  # class or function, from the AST
        node = ast.parse(u["source"]).body[0]
        kind[u["name"]] = "C" if isinstance(node, ast.ClassDef) else "f"
    mapping = {n: f"{'Cls' if kind[n] == 'C' else 'fn'}_{k}" for n, k in zip(names, nums)}

    new_units = {}
    for uid, u in units.items():
        src = rename_src(u["source"], mapping) + "\n"
        new_units[uid] = {**u, "orig_name": u["name"], "name": mapping[u["name"]],
                          "source": src, "chars": len(src)}

    pkg = importlib.import_module(args.lib)
    pkg_dir = os.path.dirname(pkg.__file__)
    ns, failed = build_flat_namespace(pkg_dir, os.path.dirname(pkg_dir), args.lib, units, mapping)

    out_items, stats = [], {"flat_namespace_failed_statements": len(failed)}
    for it in items:
        setup = drop_lib_imports(it["setup"], args.lib)
        setup = rename_src(setup, mapping) + "\n" if setup.strip() else ""
        expr = rename_src(it["expr"], mapping, mode="eval")
        try:
            ans, trace = run_flat(ns, setup, expr)
        except Exception:
            stats["skip_renamed_error"] = stats.get("skip_renamed_error", 0) + 1
            continue
        if ans != it["answer"]:
            stats["skip_answer_changed"] = stats.get("skip_answer_changed", 0) + 1
            continue
        core_new = [u for u in trace if u in set(it["core_fragments"])]
        if set(core_new) != set(it["core_fragments"]):
            stats["skip_trace_changed"] = stats.get("skip_trace_changed", 0) + 1
            continue
        out_items.append({**it, "orig_lib_setup": it["setup"], "orig_lib_expr": it["expr"],
                          "setup": setup, "expr": expr, "renamed": True})

    with open(args.out + "_items.jsonl", "w", encoding="utf-8") as f:
        for it in out_items:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")
    with open(args.out + "_units.json", "w", encoding="utf-8") as f:
        json.dump(new_units, f, ensure_ascii=False, indent=1)
    with open(args.out + "_mapping.json", "w", encoding="utf-8") as f:
        json.dump(mapping, f, indent=1)

    stats["items_in"] = len(items)
    stats["items_verified"] = len(out_items)
    for src in ("doctest", "synth"):
        ks = {}
        for it in out_items:
            if it["source"] == src and it["mutated"]:
                ks[it["k_core"]] = ks.get(it["k_core"], 0) + 1
        stats[f"{src}_mutated_k_core"] = dict(sorted(ks.items()))
    print(json.dumps(stats, indent=1))
    if failed:
        print("flat namespace: statements that never executed:", failed[:8])


if __name__ == "__main__":
    main()
